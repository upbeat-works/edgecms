interface ConsentCapability {
	endpoint: string;
	type: string;
	documentSnapshotToken: string;
	expiresAt: string;
}

beforeEach(resetDb);

async function activeLegalDocument() {
	const seeded = await seedActiveLegalDocument();
	const response = await documentLoader({
		request: new Request(
			`https://cms.test/edge-cms/public/legal/${seeded.document.slug}/${seeded.locale}`,
		),
		params: { slug: seeded.document.slug, locale: seeded.locale },
	} as never);
	const body = (await response.json()) as {
		consent?: ConsentCapability;
		releaseHash: string;
	};
	return { seeded, response, body };
}

async function submitConsent(
	consent: ConsentCapability,
	overrides: Record<string, unknown> = {},
) {
	return SELF.fetch(`https://cms.test${consent.endpoint}`, {
		method: 'POST',
		headers: {
			'Content-Type': 'application/json',
			Origin: 'https://cms.test',
		},
		body: JSON.stringify({
			type: consent.type,
			subjectId: 'sub_2jv6z8n4q9',
			domain: 'client.example',
			givenAt: Date.now(),
			documentSnapshotToken: consent.documentSnapshotToken,
			...overrides,
		}),
	});
}

async function submitConsentDirectly(
	consent: ConsentCapability,
	overrides: Record<string, unknown> = {},
) {
	return handleConsentRequest(
		new Request(`https://cms.test${consent.endpoint}`, {
			method: 'POST',
			headers: {
				'Content-Type': 'application/json',
				Origin: 'https://cms.test',
			},
			body: JSON.stringify({
				type: consent.type,
				subjectId: 'sub_2jv6z8n4q9',
				domain: 'client.example',
				givenAt: Date.now(),
				documentSnapshotToken: consent.documentSnapshotToken,
				...overrides,
			}),
		}),
		env,
	);
}

async function storedConsentMetadata(): Promise<Record<string, unknown>> {
	const storedConsent = await env.DB.prepare(
		'SELECT metadata FROM c15t_consent',
	).first<{ metadata: number[] }>();
	if (!storedConsent) return {};
	return JSON.parse(
		new TextDecoder().decode(new Uint8Array(storedConsent.metadata)),
	) as Record<string, unknown>;
}

interface ForeignKeyContract {
	from: string;
	table: string;
	on_update: string;
	on_delete: string;
}

async function foreignKeys(table: string): Promise<ForeignKeyContract[]> {
	const result = await env.DB.prepare(
		`PRAGMA foreign_key_list(${table})`,
	).all<ForeignKeyContract>();
	return result.results
		.map(({ from, table, on_update, on_delete }) => ({
			from,
			table,
			on_update,
			on_delete,
		}))
		.sort((left, right) => left.from.localeCompare(right.from));
}

