	it('stops reading a chunked consent submission at the size limit', async () => {
		let cancelled = false;
		let closeTimer: ReturnType<typeof setTimeout> | undefined;
		const body = new ReadableStream<Uint8Array>({
			start(controller) {
				controller.enqueue(new Uint8Array(64 * 1024 + 1));
				closeTimer = setTimeout(() => controller.close(), 10);
			},
			cancel() {
				cancelled = true;
				if (closeTimer) clearTimeout(closeTimer);
			},
		});
		const request = new Request(
			'https://cms.test/edge-cms/consent/subjects',
			{
				method: 'POST',
				headers: {
					'Content-Type': 'application/json',
					Origin: 'https://cms.test',
				},
				body,
			} as RequestInit,
		);

		const response = await handleConsentRequest(request, env);

		expect(response.status).toBe(413);
		expect(cancelled).toBe(true);
	});

